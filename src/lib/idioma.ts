export function traducirCategoria(idioma: Idioma, nombre: string): string {
  if (idioma !== "en") return nombre;
  const clave = nombre.normalize("NFD").replace(/[\u0300-\u036f]/g, "").toLocaleLowerCase().trim();
  return categoriasEn[clave] ?? nombre;
}
